#!/usr/bin/env node
// Validates every data file, writes data.bundle.js (what the app loads) and art/SCENE-PROMPTS.md (picture prompts).
//   node scripts/build-data.mjs            -> check + build
//   node scripts/build-data.mjs --strict   -> missing pictures/audio also count as errors (use before release)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rd = f => JSON.parse(fs.readFileSync(path.join(root, f), 'utf8'));
const exists = f => fs.existsSync(path.join(root, f));
const strict = process.argv.includes('--strict');
const LANGS = ['gu', 'hi', 'en'];
const errors = [], warns = [];
const err = m => errors.push(m), warn = m => (strict ? errors : warns).push(m);

const ui = rd('data/ui.json'), chars = rd('data/characters.json'), slots = rd('data/slots.json'), style = rd('data/style.json');
const stories = {};
for (const f of fs.readdirSync(path.join(root, 'data/stories')).filter(f => f.endsWith('.json')).sort()) {
  const s = rd('data/stories/' + f); stories[s.id] = s;
  if (s.id + '.json' !== f) err(`${f}: id "${s.id}" must match the file name`);
}

// 1. UI strings: all three languages
for (const [k, v] of Object.entries(ui)) for (const l of LANGS) if (!v[l]) err(`ui.json "${k}": missing ${l}`);

// 2. characters: names in all languages
for (const [id, c] of Object.entries(chars)) for (const l of LANGS) if (!c.names?.[l]) err(`characters.json "${id}": name missing in ${l}`);

// 3. UNIQUENESS: one character = one alphabet slot, across every alphabet
const seen = {};
for (const [alpha, map] of Object.entries(slots)) {
  if (alpha.startsWith('_')) continue;
  for (const [letter, id] of Object.entries(map)) {
    if (!chars[id]) { err(`slots.json ${alpha}.${letter}: unknown character "${id}"`); continue; }
    const key = `${alpha}.${letter}`;
    if (seen[id]) err(`REPEAT: "${id}" is used for both ${seen[id]} and ${key}. Give one of them a different character.`);
    else seen[id] = key;
  }
}

// 4. stories
const needTxt = (where, o) => { for (const l of LANGS) if (!o?.[l] || !String(o[l]).trim()) err(`${where}: missing ${l}`); };
for (const s of Object.values(stories)) {
  const [alpha, letter] = s.id.split('-');
  if (slots[alpha]?.[letter] !== s.char) err(`${s.id}: char "${s.char}" does not match slots.json (${slots[alpha]?.[letter]})`);
  needTxt(`${s.id} tag`, s.tag); needTxt(`${s.id} lesson`, s.lesson);
  if (!s.scenes?.length) err(`${s.id}: needs scenes`);
  else if (s.scenes.length < 4 || s.scenes.length > 8) warn(`${s.id}: ${s.scenes.length} scenes (aim for 5-7)`);
  (s.scenes || []).forEach((sc, i) => {
    const w = `${s.id} scene ${sc.id}`;
    if (sc.id !== i + 1) err(`${w}: scene ids must be 1,2,3… in order`);
    needTxt(w + ' text', sc.text);
    for (const l of LANGS) if (sc.text?.[l] && sc.text[l].length > 520) warn(`${w}: ${l} text is ${sc.text[l].length} characters (keep each scene short for small children)`);
    for (const k of ['setting', 'action', 'expression', 'camera']) if (!sc.shot?.[k]) err(`${w}: shot.${k} missing`);
    for (const who of sc.shot?.who || []) if (!chars[who]?.look) err(`${w}: character "${who}" has no "look" in characters.json`);
    if (!exists(`art/scenes/${letter}/${sc.id}.webp`)) warn(`${w}: picture art/scenes/${letter}/${sc.id}.webp not added yet`);
    for (const l of LANGS) if (!exists(`audio/${l}/${letter}-${sc.id}.mp3`)) warn(`${w}: audio/${l}/${letter}-${sc.id}.mp3 not made yet`);
  });
  (s.points || []).forEach((p, i) => needTxt(`${s.id} points[${i}]`, p));
  (s.words || []).forEach((p, i) => needTxt(`${s.id} words[${i}]`, p));
  (s.quiz || []).forEach((q, i) => {
    needTxt(`${s.id} quiz[${i}].q`, q.q);
    for (const l of LANGS) if (q.a?.[l]?.length !== 3) err(`${s.id} quiz[${i}]: ${l} needs exactly 3 answers (first one is the right one)`);
  });
}

// 5. bundle for the app
fs.writeFileSync(path.join(root, 'data.bundle.js'),
  '// GENERATED by scripts/build-data.mjs — edit the files in data/, not this one.\nwindow.DATA=' + JSON.stringify({ ui, chars, slots, stories }) + ';\n');

// 6. picture prompts, one per scene
let md = `# Scene picture prompts (generated — do not edit by hand)\n\nStyle for every picture: ${style.style}\n\nFormat: ${style.format}\n\nContinuity: ${style.continuity}\n\nSafety: ${style.safety}\n\nSave as \`art/scenes/<LETTER>/<scene number>.webp\`. Make scene 1 first and use it as the reference image for the rest of that story.\n`;
for (const s of Object.values(stories)) {
  const letter = s.id.split('-')[1];
  md += `\n---\n\n## ${letter} — ${chars[s.char].names.en} (${s.scenes.length} scenes)\n`;
  for (const sc of s.scenes) {
    const looks = sc.shot.who.map(w => `${chars[w].names.en}: ${chars[w].look}`).join('. ');
    md += `\n### ${letter}/${sc.id}  ·  mood: ${sc.mood}\n\n> ${style.style}. Setting: ${sc.shot.setting}. Characters — ${looks}. Action: ${sc.shot.action}. Expressions: ${sc.shot.expression}. Camera: ${sc.shot.camera}. ${style.format} ${style.safety}${sc.id > 1 ? ' ' + style.continuity : ''}\n`;
  }
}
fs.writeFileSync(path.join(root, 'art/SCENE-PROMPTS.md'), md);

// report
const nSc = Object.values(stories).reduce((n, s) => n + s.scenes.length, 0);
console.log(`characters: ${Object.keys(chars).length} · alphabet slots: ${Object.keys(seen).length} · stories with scenes: ${Object.keys(stories).length} (${nSc} scenes)`);
if (warns.length) console.log(`\n${warns.length} to-do (not errors):\n  - ` + warns.join('\n  - '));
if (errors.length) { console.error(`\n${errors.length} ERROR(S):\n  x ` + errors.join('\n  x ')); process.exit(1); }
console.log('\nOK: data is valid. Wrote data.bundle.js and art/SCENE-PROMPTS.md');
